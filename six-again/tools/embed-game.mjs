// Embeds web/index.html into game/gameHtml.ts so the app bundles the game with no file access at runtime.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const html = readFileSync(join(root, 'web', 'index.html'), 'utf8');
const out = `// Generated by tools/embed-game.mjs from web/index.html. Do not edit by hand.\nexport const GAME_HTML: string = ${JSON.stringify(html)};\n`;
writeFileSync(join(root, 'game', 'gameHtml.ts'), out);
console.log(`game/gameHtml.ts written (${(out.length / 1e6).toFixed(2)} MB)`);
